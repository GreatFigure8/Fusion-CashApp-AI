def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _default_text(key: ConfigKey[Any]) -> str:
    if key in REQUIRED_KEYS:
        return "(required)"
    dumped = key.dump(key.default)
    return f"`{json.dumps(dumped, sort_keys=True)}`"


def _type_text(key: ConfigKey[Any]) -> str:
    tp = key.type
    return getattr(tp, "__name__", None) or str(tp).replace("typing.", "")


def render_settings_doc() -> str:
    lines: list[str] = [
        "# Settings",
        "",
        "Generated by `python -m cashapp.tools.settings_doc`; do not edit by hand.",
        "",
        "Every setting except the database connection (and the few bootstrap values below) is a",
        "DB config key. Keys are edited in Settings by an admin, with a reason, and each change",
        "is versioned and audited. A key marked *restart* is read once when a process starts;",
        "all others take effect on the next read (within the cache window, 15 seconds). A key",
        "marked *secret* holds a Vault secret OCID, never the secret itself.",
        "",
        "## Bootstrap environment",
        "",
        "These are read from the process environment because they are needed before the database",
        "can be read. Any other `CASHAPP_*` variable stops the process at start-up.",
        "",
        "| Variable | Why it is not a DB key |",
        "|---|---|",
    ]
    for name in sorted(BOOTSTRAP_ENV_NAMES):
        lines.append(f"| `{name}` | {_cell(_BOOTSTRAP_REASONS.get(name, ''))} |")
    lines += [
        "",
        "Also read through `cashapp.settings`: `OCI_RESOURCE_PRINCIPAL_VERSION` (injected by the",
        "platform; selects the resource-principal signer).",
        "",
        "### Tool-only variables",
        "",
        "| Variable | Note |",
        "|---|---|",
    ]
    for name in sorted(TOOL_ENV_NAMES):
        lines.append(f"| `{name}` | {_cell(_TOOL_REASONS.get(name, ''))} |")
    lines += [
        "",
        "### Web environment",
        "",
        "| Variable | Why it is needed before Next.js can call the API |",
        "|---|---|",
    ]
    lines += [f"| `{name}` | {_cell(reason)} |" for name, reason in _WEB_ENV]
    lines += ["", "## Keys", ""]
    by_group: dict[str, list[ConfigKey[Any]]] = {}
    for key in CONFIG_KEYS.values():
        by_group.setdefault(key.group, []).append(key)
    for group in sorted(by_group, key=lambda g: (CONFIG_GROUPS[g].order, g)):
        spec = CONFIG_GROUPS[group]
        lines += [
            f"### {spec.label} (`{group}`)",
            "",
            spec.description,
            "",
            "| Key | Type | Default | Flags | Description |",
            "|---|---|---|---|---|",
        ]
        for key in by_group[group]:
            flags = [
                flag
                for flag, on in (
                    ("restart", key.restart_required),
                    ("secret", key.secret_ref),
                    ("admin", key.admin_only_write),
                )
                if on
            ]
            lines.append(
                f"| `{key.name}` | `{_cell(_type_text(key))}` | {_cell(_default_text(key))} "
                f"| {', '.join(flags)} | {_cell(key.description)} |"
            )
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"
